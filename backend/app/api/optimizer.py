"""
UrbanSage AI — Optimizer & Decision Support API Router (Stage 5)
================================================================
FastAPI endpoints for running the HiGHS MILP intervention optimizer,
computing bounded citizen-report-derived need signals, and conducting
explainable trade-off comparisons against baseline municipal plans.

Endpoints:
----------
- GET  /api/optimizer/config: Retrieve default config, wards, and interventions list.
- POST /api/optimizer/run: Execute optimizer (baseline or citizen report-informed).
- POST /api/optimizer/compare: Produce side-by-side trade-off comparison between baseline and report-informed plans.
- POST /api/optimizer/scenarios: Execute stress-test scenario simulations.

Privacy & Security:
-------------------
All endpoints preserve zero reporter contact leaks and operate strictly on
aggregated, bounded mathematical need signals.
"""

