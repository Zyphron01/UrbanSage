@router.get(
    "/plans/{plan_id}",
    response_model=BudgetPlan,
    status_code=status.HTTP_200_OK,
    summary="Get budget plan details",
    description="Retrieves a budget plan and all associated ward/intervention line items.",
)
def get_budget_plan(
    plan_id: str,
    gov_repo: GovernanceRepository = Depends(get_governance_repository),
) -> BudgetPlan:
    plan = gov_repo.get_budget_plan(plan_id)
    if not plan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Budget plan '{plan_id}' not found.",
        )
    return plan


@router.post(
    "/plans/{plan_id}/approve",
    response_model=BudgetPlan,
    status_code=status.HTTP_200_OK,
    summary="Approve budget plan and commit authorized allocations",
    description="Transitions plan to 'approved' and authorizes capital projects in the financial accountability ledger.",
)
def approve_budget_plan(
    plan_id: str,
    user: AuthenticatedUser = Depends(require_admin_role),
    gov_repo: GovernanceRepository = Depends(get_governance_repository),
    acc_repo: AccountabilityRepository = Depends(get_accountability_repository),
) -> BudgetPlan:
    plan = gov_repo.get_budget_plan(plan_id)
    if not plan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Budget plan '{plan_id}' not found.",
        )

    approved_plan = gov_repo.approve_budget_plan(plan_id=plan_id, approved_by=user.user_id)

    # Convert line items to official allocations in the capital accountability ledger
    for item in approved_plan.items:
        alloc_create = AllocationCreate(
            title=f"{item.intervention_name} in {item.neighbourhood_name}",
            neighbourhood_id=item.neighbourhood_id,
            neighbourhood_name=item.neighbourhood_name,
            intervention_id=item.intervention_id,
            intervention_name=item.intervention_name,
            category=item.category,
            allocated_amount_lakh=item.total_cost_lakh,
            planned_units=item.units,
            fiscal_year="2026-2027",
            council_resolution_ref=f"BBMP/RES/{plan_id}",
            source_optimizer_run_id=plan_id,
        )
        try:
            acc_repo.create_allocation(alloc_create, authorized_by=user.user_id)
        except Exception as e:
            logger.warning("Failed to automatically commit allocation for %s: %s", item.item_id, e)

    return approved_plan

