@router.post(
    "/run",
    response_model=OptimizationRunResponse,
    summary="Execute optimization solver",
    description="Executes SciPy HiGHS MILP under capital, equity, capacity, and diversity bounds.",
)
def run_optimization(
    payload: OptimizationRunRequest,
    repo: BaseCitizenReportRepository = Depends(get_report_repository),
) -> OptimizationRunResponse:
    bundle = load_default_dataset()

    # Normalize weights
    tot_w = payload.priority_heat + payload.priority_flood + payload.priority_water
    if tot_w <= 0:
        raise HTTPException(status_code=400, detail="Priority weights sum must be strictly positive.")

    weights = PriorityWeights(
        heat=payload.priority_heat / tot_w,
        flood=payload.priority_flood / tot_w,
        water=payload.priority_water / tot_w,
    )

    report_signals = None
    audit = None

    if payload.include_citizen_reports:
        # Load reports from repository
        all_reports = repo.list_reports(limit=1000)
        signal_engine = ReportNeedSignalEngine()
        audit = signal_engine.compute_signals(
            reports=all_reports,
            neighbourhoods=bundle.neighbourhoods,
        )
        report_signals = audit.to_signal_map()

    config = EngineConfig(
        budget_lakh=payload.budget_lakh,
        equity_threshold=payload.equity_threshold,
        priority_weights=weights,
        equity_weight=payload.equity_weight,
        max_interventions_per_neighbourhood=payload.max_interventions_per_neighbourhood,
        report_need_signals=report_signals,
    )

    optimizer = UrbanSageOptimizer(bundle)
    result = optimizer.solve(config)

    if result.status.value not in ("OPTIMAL", "FEASIBLE"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Optimization failed: {result.solver_message}",
        )

    return OptimizationRunResponse(result=result, need_audit=audit)


@router.post(
    "/compare",
    response_model=DecisionComparisonResult,
    summary="Compare baseline vs report-informed optimization",
    description=(
        "Executes both baseline (uninformed) and citizen report-informed solvers, "
        "returning granular allocation diffs, budget movements, equity impacts, and explanations."
    ),
)
def compare_optimization(
    payload: OptimizationRunRequest,
    repo: BaseCitizenReportRepository = Depends(get_report_repository),
) -> DecisionComparisonResult:
    bundle = load_default_dataset()

    tot_w = payload.priority_heat + payload.priority_flood + payload.priority_water
    if tot_w <= 0:
        raise HTTPException(status_code=400, detail="Priority weights sum must be strictly positive.")

    weights = PriorityWeights(
        heat=payload.priority_heat / tot_w,
        flood=payload.priority_flood / tot_w,
        water=payload.priority_water / tot_w,
    )

    # 1. Baseline Run (No citizen signals)
    base_config = EngineConfig(
        budget_lakh=payload.budget_lakh,
        equity_threshold=payload.equity_threshold,
        priority_weights=weights,
        equity_weight=payload.equity_weight,
        max_interventions_per_neighbourhood=payload.max_interventions_per_neighbourhood,
        report_need_signals=None,
    )
    optimizer = UrbanSageOptimizer(bundle)
    base_result = optimizer.solve(base_config)

    # 2. Integrated Run (With citizen signals)
    all_reports = repo.list_reports(limit=1000)
    signal_engine = ReportNeedSignalEngine()
    audit = signal_engine.compute_signals(
        reports=all_reports,
        neighbourhoods=bundle.neighbourhoods,
    )
    report_signals = audit.to_signal_map()

    integ_config = EngineConfig(
        budget_lakh=payload.budget_lakh,
        equity_threshold=payload.equity_threshold,
        priority_weights=weights,
        equity_weight=payload.equity_weight,
        max_interventions_per_neighbourhood=payload.max_interventions_per_neighbourhood,
        report_need_signals=report_signals,
    )
    integ_result = optimizer.solve(integ_config)

    return compare_decision_portfolios(
        baseline=base_result,
        integrated=integ_result,
        bundle=bundle,
        need_audit=audit,
    )


@router.post(
    "/scenarios/run",
    response_model=ScenarioComparison,
    summary="Run policy stress-test scenario",
    description="Stress-tests plan resilience against budget cuts, climate anomalies, or policy shifts.",
)
def run_scenario(
    payload: ScenarioRunRequest,
    repo: BaseCitizenReportRepository = Depends(get_report_repository),
) -> ScenarioComparison:
    bundle = load_default_dataset()

    weights = None
    if payload.priority_heat is not None and payload.priority_flood is not None and payload.priority_water is not None:
        tot_w = payload.priority_heat + payload.priority_flood + payload.priority_water
        if tot_w > 0:
            weights = PriorityWeights(
                heat=payload.priority_heat / tot_w,
                flood=payload.priority_flood / tot_w,
                water=payload.priority_water / tot_w,
            )

    report_signals = None
    if payload.include_citizen_reports:
        all_reports = repo.list_reports(limit=1000)
        signal_engine = ReportNeedSignalEngine()
        audit = signal_engine.compute_signals(
            reports=all_reports,
            neighbourhoods=bundle.neighbourhoods,
        )
        report_signals = audit.to_signal_map()

    base_config = EngineConfig(
        budget_lakh=500.0,
        equity_threshold=0.30,
        report_need_signals=report_signals,
    )

    scenario_config = ScenarioConfig(
        scenario_id="SCEN-API-RUN",
        name=payload.name,
        description=payload.description or "API scenario simulation execution",
        scenario_type=payload.scenario_type,
        budget_lakh=payload.budget_lakh,
        equity_threshold=payload.equity_threshold,
        priority_weights=weights,
        flood_risk_multiplier=payload.flood_multiplier if payload.flood_multiplier is not None else 1.0,
        heat_risk_multiplier=payload.heat_multiplier if payload.heat_multiplier is not None else 1.0,
        water_stress_multiplier=payload.water_multiplier if payload.water_multiplier is not None else 1.0,
    )

    simulator = UrbanSageSimulator(bundle, base_config)
    return simulator.run_scenario(scenario_config)


