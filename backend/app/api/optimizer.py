router = APIRouter(prefix="/api/optimizer", tags=["Optimizer & Decision Support"])


class OptimizationRunRequest(BaseModel):
    """Payload to trigger an optimization execution."""
    budget_lakh: float = Field(default=500.0, gt=0, description="Capital budget in Lakh INR")
    equity_threshold: float = Field(default=0.30, ge=0.0, le=1.0, description="Minimum spend fraction for high-vulnerability wards")
    priority_heat: float = Field(default=0.35, ge=0.0, le=1.0)
    priority_flood: float = Field(default=0.35, ge=0.0, le=1.0)
    priority_water: float = Field(default=0.30, ge=0.0, le=1.0)
    equity_weight: float = Field(default=0.20, ge=0.0, le=2.0)
    max_interventions_per_neighbourhood: int = Field(default=3, ge=1, le=10)
    include_citizen_reports: bool = Field(default=True, description="Whether to incorporate audited citizen need signals")


class OptimizationRunResponse(BaseModel):
    """Response containing optimization results and signal audits."""
    result: PortfolioResult
    need_audit: NeedSignalAudit | None = None
    data_disclaimer: dict[str, Any] = Field(
        default_factory=lambda: {
            "is_modeled_estimate": True,
            "synthetic_baseline": True,
            "notice": "All outcomes are mathematical estimates generated by SciPy HiGHS MILP, not observed real-world impacts.",
        }
    )


class ScenarioRunRequest(BaseModel):
    """Payload to trigger a scenario simulation."""
    scenario_type: ScenarioType
    name: str = "Simulated Scenario"
    description: str = ""
    budget_lakh: float | None = None
    equity_threshold: float | None = None
    priority_heat: float | None = None
    priority_flood: float | None = None
    priority_water: float | None = None
    flood_multiplier: float | None = Field(default=None, ge=0.0, le=3.0)
    heat_multiplier: float | None = Field(default=None, ge=0.0, le=3.0)
    water_multiplier: float | None = Field(default=None, ge=0.0, le=3.0)
    include_citizen_reports: bool = Field(default=True)


